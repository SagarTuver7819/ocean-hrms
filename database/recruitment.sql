-- Recruitment module (QR career form, candidates, interviews)

CREATE TABLE IF NOT EXISTS candidates (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  application_no VARCHAR(30) NOT NULL UNIQUE,
  public_token CHAR(32) NOT NULL UNIQUE,
  department_id INT UNSIGNED NULL,
  designation_id INT UNSIGNED NULL,
  position_other VARCHAR(150) NULL,
  employment_type ENUM('full_time','intern','contract','part_time') DEFAULT 'full_time',
  work_mode ENUM('office','hybrid','remote') DEFAULT 'office',
  source VARCHAR(60) NULL,
  referred_by VARCHAR(120) NULL,
  first_name VARCHAR(80) NOT NULL,
  middle_name VARCHAR(80) NULL,
  last_name VARCHAR(80) NOT NULL,
  mobile VARCHAR(20) NOT NULL,
  alt_mobile VARCHAR(20) NULL,
  parent_mobile VARCHAR(20) NULL,
  email VARCHAR(150) NOT NULL,
  date_of_birth DATE NULL,
  gender ENUM('male','female','other') NULL,
  marital_status VARCHAR(40) NULL,
  address TEXT NULL,
  city VARCHAR(80) NULL,
  state VARCHAR(80) NULL,
  pincode VARCHAR(20) NULL,
  aadhaar_number VARCHAR(20) NULL,
  pan_number VARCHAR(20) NULL,
  is_fresher TINYINT(1) NOT NULL DEFAULT 0,
  total_experience_months INT NOT NULL DEFAULT 0,
  current_ctc DECIMAL(12,2) NULL,
  expected_ctc DECIMAL(12,2) NULL,
  offered_salary DECIMAL(12,2) NULL,
  joining_date DATE NULL,
  probation_months TINYINT UNSIGNED NULL,
  offer_valid_till DATE NULL,
  selected_at DATETIME NULL,
  notice_period VARCHAR(40) NULL,
  current_location VARCHAR(120) NULL,
  ready_to_relocate TINYINT(1) DEFAULT 0,
  primary_skills TEXT NULL,
  secondary_skills TEXT NULL,
  certifications TEXT NULL,
  github_url VARCHAR(255) NULL,
  linkedin_url VARCHAR(255) NULL,
  portfolio_url VARCHAR(255) NULL,
  best_project TEXT NULL,
  why_join TEXT NULL,
  photo_path VARCHAR(255) NULL,
  resume_path VARCHAR(255) NULL,
  declaration TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('new','shortlisted','interview','technical_round','hr_round','selected','offered','joined','on_hold','rejected') NOT NULL DEFAULT 'new',
  hr_remarks TEXT NULL,
  employee_id INT UNSIGNED NULL,
  ip_address VARCHAR(45) NULL,
  created_at DATETIME NULL,
  updated_at DATETIME NULL,
  INDEX idx_cand_status (status),
  INDEX idx_cand_mobile (mobile),
  FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
  FOREIGN KEY (designation_id) REFERENCES designations(id) ON DELETE SET NULL,
  FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS candidate_education (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  candidate_id INT UNSIGNED NOT NULL,
  degree VARCHAR(120) NULL,
  institute VARCHAR(150) NULL,
  specialization VARCHAR(120) NULL,
  passing_year VARCHAR(10) NULL,
  percentage_grade VARCHAR(40) NULL,
  FOREIGN KEY (candidate_id) REFERENCES candidates(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS candidate_experience (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  candidate_id INT UNSIGNED NOT NULL,
  company VARCHAR(150) NULL,
  designation VARCHAR(120) NULL,
  from_month CHAR(7) NULL,
  to_month CHAR(7) NULL,
  is_current TINYINT(1) DEFAULT 0,
  tech_stack VARCHAR(255) NULL,
  responsibilities TEXT NULL,
  FOREIGN KEY (candidate_id) REFERENCES candidates(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS candidate_interviews (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  candidate_id INT UNSIGNED NOT NULL,
  round ENUM('screening','technical','machine_test','managerial','hr') NOT NULL DEFAULT 'technical',
  interview_at DATETIME NULL,
  mode ENUM('in_person','video','phone') DEFAULT 'in_person',
  interviewer VARCHAR(120) NULL,
  technical_score TINYINT NULL,
  communication_score TINYINT NULL,
  problem_solving_score TINYINT NULL,
  attitude_score TINYINT NULL,
  result ENUM('pending','pass','fail','hold') NOT NULL DEFAULT 'pending',
  feedback TEXT NULL,
  created_by INT UNSIGNED NULL,
  created_at DATETIME NULL,
  FOREIGN KEY (candidate_id) REFERENCES candidates(id) ON DELETE CASCADE
) ENGINE=InnoDB;
